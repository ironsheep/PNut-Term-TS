#!/usr/bin/env node
/**
 * Regenerate the PASM2 disassembler regression corpus from authoritative
 * pnut-ts output.
 *
 *   node scripts/claude/gen-disasm-corpus.mjs
 *
 * Requires `pnut-ts` on PATH (compile-only; no hardware). Compiles
 * tests/fixtures/pasm2_corpus.spin2, extracts the encoded longs between the
 * two sentinel longs ($DEADBEEF .. $FEEDFACE), pairs each with the source
 * mnemonic (first token on its line), and writes tests/fixtures/pasm2_corpus.json.
 *
 * The committed JSON is what tests/disassemblerCorpus.test.ts consumes, so the
 * test stays self-contained (pnut-ts is NOT needed at test time). Re-run this
 * whenever the fixture changes, on a machine with pnut-ts available.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..', '..');
const FIXTURE_DIR = join(REPO, 'tests', 'fixtures');
const SRC = join(FIXTURE_DIR, 'pasm2_corpus.spin2');
const BIN = join(FIXTURE_DIR, 'pasm2_corpus.bin');
const OUT = join(FIXTURE_DIR, 'pasm2_corpus.json');

const START_SENTINEL = 0xdeadbeef;
const END_SENTINEL = 0xfeedface;

// Directives / data ops that appear in the region but emit no instruction long
// we want to name (the sentinels are `long`s; org/fit emit nothing).
const SKIP_TOKENS = new Set(['org', 'orgh', 'fit', 'alignl', 'alignw', 'res', 'long', 'word', 'byte']);

function parseSourceMnemonics() {
  const lines = readFileSync(SRC, 'utf8').split(/\r?\n/);
  const startLine = lines.findIndex((l) => l.includes('DEAD_BEEF'));
  const endLine = lines.findIndex((l) => l.includes('FEED_FACE'));
  if (startLine < 0 || endLine < 0 || endLine <= startLine) {
    throw new Error('Could not locate both corpus sentinels in source');
  }
  const mnemonics = [];
  for (let i = startLine + 1; i < endLine; i++) {
    let t = lines[i].split("'")[0].trim(); // drop trailing comment
    if (t === '') continue;
    const first = t.split(/\s+/)[0].toLowerCase();
    if (SKIP_TOKENS.has(first)) continue;
    mnemonics.push(first);
  }
  return mnemonics;
}

function compile() {
  execFileSync('pnut-ts', ['-q', 'pasm2_corpus.spin2'], { cwd: FIXTURE_DIR, stdio: 'pipe' });
}

function extractLongs() {
  const buf = readFileSync(BIN);
  let start = -1;
  for (let i = 0; i + 4 <= buf.length; i++) {
    if (buf.readUInt32LE(i) === START_SENTINEL) {
      start = i;
      break;
    }
  }
  if (start < 0) throw new Error('Start sentinel not found in compiled image');
  const longs = [];
  for (let i = start + 4; i + 4 <= buf.length; i += 4) {
    const word = buf.readUInt32LE(i);
    if (word === END_SENTINEL) return longs;
    longs.push(word >>> 0);
  }
  throw new Error('End sentinel not found after start sentinel');
}

function main() {
  compile();
  const mnemonics = parseSourceMnemonics();
  const longs = extractLongs();
  if (mnemonics.length !== longs.length) {
    throw new Error(
      `Corpus mismatch: ${mnemonics.length} source mnemonics vs ${longs.length} encoded longs. ` +
        `A non-instruction line likely slipped into the sentinel region (or a directive emitted a long).`
    );
  }
  const corpus = longs.map((word, i) => ({
    addr: i, // cog address index (org 0); used for branch-target rendering
    word: '0x' + word.toString(16).padStart(8, '0'),
    mnem: mnemonics[i]
  }));
  const json = {
    _comment:
      'GENERATED by scripts/claude/gen-disasm-corpus.mjs from tests/fixtures/pasm2_corpus.spin2 ' +
      'via authoritative pnut-ts encoding. Do not hand-edit; edit the .spin2 and regenerate.',
    count: corpus.length,
    corpus
  };
  writeFileSync(OUT, JSON.stringify(json, null, 2) + '\n');
  console.log(`Wrote ${OUT}: ${corpus.length} instructions`);
}

main();
