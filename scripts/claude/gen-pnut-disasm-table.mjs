#!/usr/bin/env node
/**
 * Generate src/classes/debugger/renderer/pnutDisasmTable.ts from PNut's own
 * disassembler table (`da_ins` .. `da_nop` in p2com.asm).
 *
 * Each source line is the `disasm` macro:
 *   disasm 'mnem   ', im, dm, sm, iv, dv, sv, disop_xxx
 * which assembles to
 *   dd (im shl 18) + (dm shl 9) + sm     ; mask
 *   dd (iv shl 18) + (dv shl 9) + sv     ; match
 *   db disop, mnem
 *
 * Usage: node scripts/claude/gen-pnut-disasm-table.mjs [path/to/p2com.asm]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const asmPath = process.argv[2] ?? '/pascal-source/P2_PNut_Public/p2com.asm';
const outPath = resolve(here, '../../src/classes/debugger/renderer/pnutDisasmTable.ts');

const asm = readFileSync(asmPath, 'latin1');
const lines = asm.split(/\r?\n/);
const start = lines.findIndex((l) => /^da_ins:/.test(l));
const end = lines.findIndex((l) => /^da_nop:/.test(l));
if (start < 0 || end < 0 || end < start) throw new Error(`da_ins/da_nop not found in ${asmPath}`);

const LINE = /disasm\s+'(.{7})',\s*([0-9A-F]+)h,\s*([0-9A-F]+)h,\s*([0-9A-F]+)h,\s*([0-9A-F]+)h,\s*([0-9A-F]+)h,\s*([0-9A-F]+)h,\s*disop_(\w+)/i;
const rows = [];
let nop = null;
for (let i = start; i <= end; i++) {
  const l = lines[i];
  if (!/\bdisasm\b/.test(l)) continue;
  const m = LINE.exec(l);
  if (!m) throw new Error(`unparsed disasm line ${i + 1}: ${l}`);
  const [, mnem, im, dm, sm, iv, dv, sv, op] = m;
  const h = (s) => parseInt(s, 16);
  const mask = ((h(im) << 18) + (h(dm) << 9) + h(sm)) >>> 0;
  const match = ((h(iv) << 18) + (h(dv) << 9) + h(sv)) >>> 0;
  const row = { mask, match, mnem, op, line: i + 1 };
  if (/^da_nop:/.test(l)) nop = row; else rows.push(row);
}
if (!nop) throw new Error('da_nop row missing');

const hex = (v) => '0x' + v.toString(16).toUpperCase().padStart(8, '0');
const digest = createHash('sha256').update(readFileSync(asmPath)).digest('hex').slice(0, 16);
const fmt = (r) => `  [${hex(r.mask)}, ${hex(r.match)}, '${r.mnem}', '${r.op}'], // p2com.asm:${r.line}`;

const out = `/** @format */
/* eslint-disable */
// GENERATED by scripts/claude/gen-pnut-disasm-table.mjs — do not edit by hand.
// Source: PNut p2com.asm \`da_ins\` (sha256 ${digest}…), ${rows.length} rows + da_nop.
// Each row: [mask, match, mnemonic (7 chars, space padded), operand handler].
// The first row whose (inst & mask) === match wins; the last row, '<error>', matches anything.

export type PnutDisasmRow = readonly [number, number, string, string];

export const PNUT_DA_INS: readonly PnutDisasmRow[] = [
${rows.map(fmt).join('\n')}
];

export const PNUT_DA_NOP: PnutDisasmRow = [${hex(nop.mask)}, ${hex(nop.match)}, '${nop.mnem}', '${nop.op}'];
`;
writeFileSync(outPath, out);
console.log(`wrote ${outPath}: ${rows.length} rows + nop (from ${asmPath}, sha256 ${digest})`);
